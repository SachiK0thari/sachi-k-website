#!/usr/bin/env node
// Rebuilds the plain-HTML (no-JavaScript) copy of the site in index.html
// from the text the real site uses, so the two never drift apart.
//
//   node scripts/sync-nojs.mjs          update index.html
//   node scripts/sync-nojs.mjs --check  only report whether it is out of date
//   node scripts/sync-nojs.mjs other.html   work on another file
//
// Source of truth: the page template inside the bundle
// (<script type="__bundler/template">): the hero text, the `projects` and
// `experience` arrays, and the footer links. Edit those, then run this.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const FILE = path.resolve(process.argv.slice(2).find(a => !a.startsWith('--')) || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'index.html'));
const START = '<!-- nojs:start (generated by scripts/sync-nojs.mjs, do not edit by hand) -->';
const END = '<!-- nojs:end -->';

const html = fs.readFileSync(FILE, 'utf8');

// 1. Pull the page template out of the bundle.
const tplMatch = html.match(/<script type="__bundler\/template">([\s\S]*?)<\/script>/);
if (!tplMatch) fail('Could not find the bundled page template.');
const tpl = JSON.parse(tplMatch[1]);

// 2. Read the arrays from the component's renderVals().
function readArray(name) {
  const at = tpl.indexOf(`${name}: [`);
  if (at < 0) fail(`Could not find "${name}: [" in the template.`);
  let i = tpl.indexOf('[', at), depth = 0, quote = null;
  const start = i;
  for (; i < tpl.length; i++) {
    const c = tpl[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
    } else if (c === '"' || c === "'" || c === '`') quote = c;
    else if (c === '[' || c === '{') depth++;
    else if (c === ']' || c === '}') { if (--depth === 0) break; }
  }
  return new Function(`return ${tpl.slice(start, i + 1)};`)();
}
const projects = readArray('projects');
const experience = readArray('experience');

// 3. Hero text and footer links from the template markup.
const strip = s => s.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const hero = tpl.match(/<div[^>]*>([^<]*)<\/div>\s*<h1[^>]*>([\s\S]*?)<\/h1>\s*<p[^>]*>([\s\S]*?)<\/p>/);
if (!hero) fail('Could not find the hero headline and paragraph.');
const [, eyebrow, headline, intro] = hero.map(strip);

const contact = tpl.slice(tpl.indexOf('id="contact"'));
const links = [...contact.matchAll(/<a href="(https?:[^"]+)"[^>]*>([^<]+)<\/a>/g)]
  .map(m => ({ href: m[1], label: strip(m[2]) }));

// 4. Render.
const esc = s => String(s)
  .replace(/&(?![a-z]+;|#\d+;)/gi, '&amp;')
  .replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const linkList = ls => ls.map(l => `<a href="${esc(l.href)}">${esc(l.label)}</a>`).join(' · ');

const out = [];
out.push(START);
out.push('  <noscript>');
out.push('    <main class="nojs">');
out.push(`      <small>${esc(eyebrow)}</small>`);
out.push(`      <h1>Sachi Kothari. ${esc(headline)}</h1>`);
out.push(`      <p>${esc(intro)}</p>`);
out.push('');
out.push('      <h2>Selected work</h2>');
for (const p of projects) {
  out.push(`      <h3>${esc(p.title)}</h3>`);
  out.push(`      <p>${esc(p.desc)}</p>`);
  if (p.links?.length) out.push(`      <p>${linkList(p.links)}</p>`);
}
out.push('');
out.push('      <h2>Experience</h2>');
for (const x of experience) {
  out.push(`      <h3>${esc(x.role)}, ${esc(x.company)}</h3>`);
  out.push(`      <p><small>${esc(x.period)} · ${esc(x.place)}</small></p>`);
  out.push('      <ul>');
  for (const pt of x.points) out.push(`        <li>${esc(pt)}</li>`);
  out.push('      </ul>');
}
out.push('');
out.push('      <h2>Contact</h2>');
out.push(`      <p>${linkList(links)}</p>`);
out.push('      <p><small>Turn on JavaScript for the full site.</small></p>');
out.push('    </main>');
out.push('  </noscript>');
out.push(END);
const block = out.join('\n');

// 5. Replace the existing block (marked, or the original unmarked one).
let re;
if (html.includes(START)) {
  re = new RegExp(escapeRe(START) + '[\\s\\S]*?' + escapeRe(END));
} else {
  re = /  <noscript>\n    <main class="nojs">[\s\S]*?<\/main>\n  <\/noscript>/;
  // Fresh export with no copy yet: put it right after <body>.
  if (!re.test(html)) re = /(?<=<body>\n)/;
}
const next = html.replace(re, () => re.source === '(?<=<body>\\n)' ? block + '\n' : block);
if (next === html && !html.includes(START)) fail('Could not find where to put the no-JavaScript copy (no <body> tag).');

if (process.argv.includes('--check')) {
  if (next === html) { console.log('No-JavaScript copy is up to date.'); process.exit(0); }
  console.log('No-JavaScript copy is OUT OF DATE. Run: node scripts/sync-nojs.mjs');
  process.exit(1);
}
if (next === html) {
  console.log('No-JavaScript copy was already up to date.');
} else {
  fs.writeFileSync(FILE, next);
  console.log(`Updated no-JavaScript copy: ${projects.length} projects, ${experience.length} roles, ${links.length} links.`);
}

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
function fail(msg) { console.error('sync-nojs: ' + msg); process.exit(2); }
